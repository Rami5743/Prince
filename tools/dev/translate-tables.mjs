/**
 * Turn SDLPoP's hard-coded tables into `src/pop/data.ts`.
 *
 *   node tools/dev/translate-tables.mjs <path to SDLPoP/src>
 *
 * The tables the game keeps in PRINCE.EXE -- the frame tables, the
 * sequence table, the level data -- are *not* taken from here: the port
 * reads those out of the real executable, which is a better source than
 * anybody's transcription of it and is already checked by
 * `tests/game/exe-tables.test.ts`. What is here is the rest: the
 * numbers that live in the game's code rather than in its data, which
 * SDLPoP has as C literals and which would otherwise have to be typed
 * out by hand.
 *
 * Typing them out by hand is exactly what this avoids. The file it
 * writes is checked in, so a build does not need the C; re-run it when
 * the C moves.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = process.argv[2];
if (!SRC) {
  console.error('usage: translate-tables.mjs <path to SDLPoP/src>');
  process.exit(2);
}

/** Every C file the tables are spread over. */
const FILES = ['data.h', 'seg002.c', 'seg003.c', 'seg005.c', 'seg006.c', 'seg007.c', 'seg008.c'];
const text = FILES.map((f) => readFileSync(join(SRC, f), 'utf8')).join('\n');

/** Strip comments so a `//` inside a table cannot swallow a line. */
function uncomment(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
}

/**
 * The body of `const <type> <name>[...] [INIT](= { ... })`.
 *
 * `INIT(= ...)` is SDLPoP's macro for "this is the definition, not just
 * the declaration"; in `data.h` the tables are written that way and
 * everywhere else they are plain initialisers.
 */
function tableBody(name) {
  const re = new RegExp(
    `\\b${name}\\s*\\[[^\\]]*\\]\\s*(?:INIT\\s*\\()?\\s*=\\s*\\{`, 'g',
  );
  const m = re.exec(text);
  if (!m) throw new Error(`no table ${name}`);
  let depth = 1;
  let i = re.lastIndex;
  while (i < text.length && depth > 0) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}') depth--;
    if (depth === 0) break;
    i++;
  }
  return uncomment(text.slice(re.lastIndex, i));
}

/** A flat table of numbers. C's `0x0F | 4` and friends are evaluated. */
function numbers(name) {
  return tableBody(name)
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .map((s) => {
      const v = Function(`"use strict";return (${s})`)();
      if (typeof v !== 'number' || !Number.isFinite(v)) {
        throw new Error(`${name}: cannot read ${JSON.stringify(s)}`);
      }
      return v;
    });
}

/** A table of structs: each `{ ... }` becomes one array of numbers. */
function structs(name, fields) {
  const body = tableBody(name);
  const rows = [...body.matchAll(/\{([^{}]*)\}/g)].map((m) => m[1]);
  return rows.map((row) => {
    const parts = row.split(',').map((s) => s.trim()).filter((s) => s.length);
    if (parts.length !== fields.length) {
      throw new Error(`${name}: ${parts.length} values for ${fields.length} fields`);
    }
    const out = {};
    parts.forEach((p, i) => {
      out[fields[i]] = Function(`"use strict";return (${p})`)();
    });
    return out;
  });
}

/** Signed-byte tables are written as signed in the C and stay signed. */
const FLAT = [
  'tbl_line', 'chtab_flip_clip', 'chtab_shift', 'y_land', 'x_bump', 'y_clip',
  'dir_front', 'dir_behind', 'tile_div_tbl', 'tile_mod_tbl', 'col_xh',
  'doortop_fram_top', 'door_fram_top', 'blueline_fram1', 'blueline_fram_y',
  'blueline_fram3', 'doortop_fram_bot', 'spikes_fram_right', 'loose_fram_right',
  'wall_fram_bottom', 'loose_fram_bottom', 'loose_fram_left', 'spikes_fram_left',
  'potion_fram_bubb', 'chomper_fram1', 'chomper_fram_bot', 'chomper_fram_top',
  'chomper_fram_y', 'spikes_fram_fore', 'chomper_fram_for', 'wall_fram_main',
  'door_fram_slice', 'floor_left_overlay', 'gate_close_speeds', 'door_delta',
  'leveldoor_close_speeds', 'y_loose_land', 'loose_sound', 'y_something',
  'strikeprob', 'restrikeprob', 'blockprob', 'impblockprob', 'advprob',
  'refractimer', 'extrastrength',
];

const PIECE = [
  'base_id', 'floor_left', 'base_y', 'right_id', 'floor_right', 'right_y',
  'stripe_id', 'topright_id', 'bottom_id', 'fore_id', 'fore_x', 'fore_y',
];
const SWORD = ['id', 'x', 'y'];

const out = [];
out.push(`/**
 * The numbers SDLPoP keeps in its code, not in the game's data.
 *
 * Generated by \`tools/dev/translate-tables.mjs\` from
 * https://github.com/NagyD/SDLPoP -- do not edit by hand. The tables
 * that live inside PRINCE.EXE are not here: those are read out of the
 * executable itself by \`src/game/exe-tables.ts\`.
 */
/* eslint-disable */
`);

for (const name of FLAT) {
  const v = numbers(name);
  out.push(`export const ${name} = [${v.join(', ')}] as const;`);
}

const tiles = structs('tile_table', PIECE);
out.push(`
/** \`piece\`: which sprite each part of a tile is drawn from. */
export interface Piece {
${PIECE.map((f) => `  readonly ${f}: number;`).join('\n')}
}

export const tile_table: readonly Piece[] = [
${tiles.map((t) => `  { ${PIECE.map((f) => `${f}: ${t[f]}`).join(', ')} },`).join('\n')}
];`);

const swords = structs('sword_tbl', SWORD);
out.push(`
/** \`sword_table_type\`: where the blade sits in each sword frame. */
export const sword_tbl: readonly { id: number; x: number; y: number }[] = [
${swords.map((s) => `  { id: ${s.id}, x: ${s.x}, y: ${s.y} },`).join('\n')}
];`);

mkdirSync(join(REPO, 'src', 'pop'), { recursive: true });
const path = join(REPO, 'src', 'pop', 'data.ts');
writeFileSync(path, out.join('\n') + '\n');
console.log(`${FLAT.length} tables, ${tiles.length} tile pieces, `
  + `${swords.length} sword frames -> ${path}`);

// ---------------------------------------------------------------- enums

/**
 * The enums, as `const` objects with the same names the C uses.
 *
 * Written to `src/pop/types.ts`. Only the ones the game's logic reads:
 * the sound, replay and menu enums are the port's own business.
 */
const typesText = stripPreproc(uncomment(readFileSync(join(SRC, 'types.h'), 'utf8')));

/**
 * Drop SDLPoP's own extensions.
 *
 * Its enums carry entries behind `#ifdef USE_...`, which are features
 * it adds to the game. The port is a port of the game as it was, so
 * the guarded branch goes and the `#else` branch -- the one that is
 * compiled with the feature off -- stays.
 */
function stripPreproc(s) {
  const out = [];
  const skip = [];
  for (const line of s.split('\n')) {
    const t = line.trim();
    const open = /^#\s*(if|ifdef|ifndef)\b(.*)$/.exec(t);
    if (open) {
      // An include guard opens a block too, and that one keeps its
      // contents; only SDLPoP's own feature switches drop theirs.
      skip.push(/\b(USE|FIX|ALLOW|ENABLE|CHECK)_\w+/.test(open[2]));
      continue;
    }
    if (/^#\s*else\b/.test(t)) {
      if (skip.length) skip[skip.length - 1] = !skip[skip.length - 1];
      continue;
    }
    if (/^#\s*endif\b/.test(t)) { skip.pop(); continue; }
    if (/^#/.test(t)) continue;
    if (!skip.includes(true)) out.push(line);
  }
  return out.join('\n');
}

const ENUMS = [
  'tiles', 'chtabs', 'blitters', 'charids', 'sword_status', 'frame_flags',
  'directions', 'actions', 'frameids', 'seqids', 'seqtbl_instructions',
  'seqtbl_sounds', 'colorids', 'timerids', 'soundids',
];

function enumBody(name) {
  const re = new RegExp(`\\benum\\s+${name}\\s*\\{`, 'g');
  const m = re.exec(typesText);
  if (!m) throw new Error(`no enum ${name}`);
  const end = typesText.indexOf('}', re.lastIndex);
  return typesText.slice(re.lastIndex, end);
}

const te = [];
te.push(`/**
 * SDLPoP's enums, under SDLPoP's names.
 *
 * Generated by \`tools/dev/translate-tables.mjs\` from
 * https://github.com/NagyD/SDLPoP -- do not edit by hand.
 */
/* eslint-disable */
`);
for (const name of ENUMS) {
  const entries = [];
  let next = 0;
  for (const part of enumBody(name).split(',')) {
    const s = part.trim();
    if (!s) continue;
    const eq = s.indexOf('=');
    let key; let value;
    if (eq < 0) {
      key = s;
      value = next;
    } else {
      key = s.slice(0, eq).trim();
      const expr = s.slice(eq + 1).trim();
      value = Function(
        '"use strict";' + entries.map(([k, v]) => `const ${k}=${v};`).join('')
        + `return (${expr});`,
      )();
    }
    if (!/^[A-Za-z_]\w*$/.test(key)) throw new Error(`${name}: odd key ${key}`);
    next = value + 1;
    entries.push([key, value]);
  }
  te.push(`export const ${name} = {\n`
    + entries.map(([k, v]) => `  ${k}: ${v},`).join('\n')
    + `\n} as const;\n`);
}
const tpath = join(REPO, 'src', 'pop', 'types.ts');
writeFileSync(tpath, te.join('\n'));
console.log(`${ENUMS.length} enums -> ${tpath}`);
